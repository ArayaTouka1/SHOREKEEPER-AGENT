function extractRelation(desc) {
  const m = desc.match(/【与\s*\{\{user\}\}\s*的关系】([\s\S]*?)(?=\n【|$)/)
  if (m) return m[1].trim()
  return desc.split('\n').slice(-6).join('\n').trim()
}

function extractAddress(desc, _id) {
  const explicit = desc.match(/称呼\s*\{\{user\}\}\s*为\s*[「"“]?([^」"”，。、\n]{1,12})/)
  if (explicit) return `称呼用户为「${explicit[1]}」。`

  const rel = desc.match(/【与\s*\{\{user\}\}\s*的关系】([\s\S]{0,900})/)
  const scope = rel ? rel[1] : desc
  const implicit = scope.match(/\{\{user\}\}\s*是\s*([^，。、；\n]{1,12}?)(?:[，。、；\n]|$)/)
  if (implicit) {
    const cand = implicit[1].replace(/[「」"“”]/g, '').replace(/^(她的|他的|那个|一个|位)/, '').trim()
    if (cand && cand.length <= 8 && !/人$|事$|东西|时候|地方|角色/.test(cand)) {
      return `称呼用户为「${cand}」。`
    }
  }
  return '称呼用户为「你」（没有特定称谓）。'
}

