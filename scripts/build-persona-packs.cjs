function readCard(id) {
  const p = join(CARDS, `${id}.json`)
  if (!existsSync(p)) return null
  try {
    return JSON.parse(readFileSync(p, 'utf-8'))
  } catch {
    return null
  }
}

function buildWorld(id, name) {
  const card = readCard(id)
  if (!card) return `# 世界观资料\n\n（角色卡缺失）\n`
  const d = card.data
  const entries = (d.character_book && d.character_book.entries) || []

  const constant = entries.filter((e) => e.constant)
  const keyword = entries.filter((e) => !e.constant)

  const lines = [`# 世界观资料`, '', `以下是 ${name} 所处的世界设定。聊到相关内容时自然使用，不要生硬地背诵。`, '']

  if (constant.length) {
    lines.push('## 常驻设定', '')
    for (const e of constant) lines.push(`- ${e.content}`)
    lines.push('')
  }

  if (keyword.length) {
    lines.push('## 关键词触发', '')
    lines.push('（以下条目在用户提到相应关键词时才会用到）', '')
    for (const e of keyword) {
      lines.push(`### ${(e.keys || []).slice(0, 5).join(' / ')}`)
      lines.push(e.content)
      lines.push('')
    }
  }

  return lines.join('\n')
}

