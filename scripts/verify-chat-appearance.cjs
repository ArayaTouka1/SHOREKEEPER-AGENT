const { _electron: electron, expect } = require('@playwright/test')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
async function main() {
  const root = path.resolve('.verification/chat-appearance')
  fs.mkdirSync(root, { recursive: true })
  const profile = fs.mkdtempSync(path.join(root, 'profile-'))
  fs.mkdirSync(path.join(profile, 'data'))
  fs.writeFileSync(path.join(profile, 'data/settings.json'), JSON.stringify({ general: { skipSplash: true }, llm: { provider: 'offline' } }))
  const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'chat-avatar-'))
  const avatar = path.join(fixture, '我的 头像#1.png')
  fs.copyFileSync(path.resolve('build/icon.png'), avatar)
  const env = { ...process.env, WORKSPACE_TEST_PROFILE: profile }; delete env.ELECTRON_RUN_AS_NODE
  const launch = () => electron.launch({ executablePath: path.resolve('.verification/electron-runtime/electron.exe'), args: ['--no-sandbox', '--in-process-gpu', path.resolve('scripts/workspace-test-host.cjs')], env, timeout: 30000 })
  let app = await launch()
  const ready = async () => { const page = await app.firstWindow(); await page.waitForSelector('.rail'); return page }
  try {
    let page = await ready()
    await app.evaluate(({ dialog }, avatar) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [avatar] }) }, avatar)
    await page.keyboard.press('Control+6')
    await page.locator('[data-section="chat"]').click()
    await page.getByRole('button', { name: '选择图片', exact: true }).click()
    await page.waitForFunction(() => [...document.querySelectorAll('.avatar img')].some(i => i.src.includes('%23') && i.naturalWidth > 0))
    console.log('PASS picked avatar with Chinese, space and # loads immediately')
    await page.evaluate(async () => {
      const b = (await window.aimis.bootstrap()).data
      const c = (await window.aimis.conversation.create(b.character.id, '界面验证')).data
      await window.aimis.message.append({ conversationId: c.id, role: 'user', text: '不不不，还是不用了。就这样的话，也可以见字如面。' })
      await window.aimis.message.append({ conversationId: c.id, role: 'character', text: '我知道了，你喜欢就好。' })
      await window.aimis.message.append({ conversationId: c.id, role: 'character', text: '总而言之，往后的路，请让我和你一起走下去吧。' })
    })
    await app.close()
    app = await launch(); page = await ready()
    await page.keyboard.press('Control+2')
    await expect(page.locator('.chat-character-title')).toHaveText('守岸人')
    await expect(page.locator('.chat-character-title')).toBeVisible()
    await expect(page.locator('.chat-page-head .page-crumb')).toHaveCount(0)
    await page.waitForFunction(() => [...document.querySelectorAll('.is-user .avatar img')].some(i => i.naturalWidth > 0))
    console.log('PASS saved avatar loads after full restart and title matches reference')
    const window = await app.browserWindow(page)
    await window.evaluate(w => w.setSize(1440, 1000))
    await page.waitForTimeout(800)
    const png = await window.evaluate(async w => (await w.webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG().toString('base64'))
    fs.writeFileSync(path.join(root, 'chat.png'), Buffer.from(png, 'base64'))
    await page.keyboard.press('Control+6')
    await page.locator('[data-section="chat"]').click()
    await page.locator('.switch-row').filter({ hasText: '显示我的头像' }).locator('button').click()
    await page.keyboard.press('Control+2')
    await expect(page.locator('.is-user .avatar, .is-user .chat-user-avatar')).toHaveCount(0)
    console.log('PASS hide user avatar applies to conversation')
  } finally { await app.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
