const { _electron: electron } = require('@playwright/test')
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
;(async () => {
  const root = path.resolve(__dirname, '..')
  const profile = fs.mkdtempSync(path.join(root, '.verification/splash-'))
  const env = { ...process.env, WORKSPACE_TEST_PROFILE: profile }; delete env.ELECTRON_RUN_AS_NODE
  const native = process.argv.includes('--native')
  const app = await electron.launch(native
    ? { executablePath: path.join(root, 'release/win-unpacked/守岸人陪伴终端.exe'), args: ['--no-sandbox', '--in-process-gpu', `--user-data-dir=${profile}`], cwd: root, env }
    : { args: ['--no-sandbox', '--in-process-gpu', path.join(__dirname, process.argv.includes('--packaged') ? 'package-test-host.cjs' : 'workspace-test-host.cjs')], cwd: root, env })
  try {
    const page = await app.firstWindow()
    await page.waitForFunction(() => !!window.aimis)
    console.log('media', await page.evaluate(() => window.aimis.splash.status()))
    await page.waitForSelector('video.splash-video', { timeout: 15000 })
    await page.waitForTimeout(2500)
    const playback = await page.locator('video.splash-video').evaluate(v => {
      const c = document.createElement('canvas'); c.width = 160; c.height = 90
      const ctx = c.getContext('2d'); ctx.drawImage(v, 0, 0, 160, 90)
      const pixels = ctx.getImageData(0, 0, 160, 90).data
      return { time: v.currentTime, width: v.videoWidth, ready: v.readyState, error: v.error?.message, nonblack: pixels.filter((n, i) => i % 4 !== 3 && n > 20).length }
    })
    assert(playback.time > 0 && playback.width > 0 && playback.nonblack > 1000 && !playback.error, JSON.stringify(playback))
    console.log('PASS default video decoded nonblack frames', playback)
    const win = await app.browserWindow(page)
    await win.evaluate(w => w.showInactive())
    await page.screenshot({ path: path.join(profile, 'splash.png') })
    assert.equal(await page.getByRole('button', { name: '跳过动画' }).count(), 0)
    assert.equal(await page.getByRole('button', { name: '我们开始吧' }).count(), 0)
    await page.locator('.splash').click({ position: { x: 40, y: 100 } })
    await page.waitForTimeout(600)
    assert.equal(await page.locator('.splash').count(), 0)
    console.log('PASS single click skips animation without any button')
    await page.keyboard.press('Control+6')
    await page.locator('[data-section="theme"]').click()
    const section = page.getByTestId('splash-settings')
    await section.scrollIntoViewIfNeeded()
    const custom = path.join(profile, 'custom # sample.mp4')
    fs.copyFileSync(path.join(root, 'resources/splash/opening.mp4'), custom)
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }) }, custom)
    await section.getByRole('button', { name: '选择自定义动画' }).click()
    await page.waitForFunction(() => document.querySelector('[data-testid="splash-settings"]')?.textContent.includes('custom # sample.mp4'))
    fs.unlinkSync(custom)
    assert((await page.evaluate(() => window.aimis.splash.status())).data.custom)
    await section.locator('video').evaluate(v => v.play())
    await page.waitForFunction(() => document.querySelector('[data-testid="splash-settings"] video')?.currentTime > 1)
    await page.screenshot({ path: path.join(profile, 'settings.png') })
    await page.reload()
    await page.waitForFunction(() => document.querySelector('video.splash-video')?.currentTime > 0.5)
    console.log('PASS custom import, managed copy and restart playback')
    await page.locator('video.splash-video').evaluate(v => { v.dispatchEvent(new Event('error')) })
    await page.waitForFunction(() => document.querySelector('.splash-brand')?.classList.contains('shown'))
    await page.locator('.splash').click({ position: { x: 40, y: 100 } })
    await page.waitForTimeout(600)
    assert.equal(await page.locator('.splash').count(), 0)
    console.log('PASS decode failure still skips by clicking anywhere')
    const reset = await page.evaluate(() => window.aimis.splash.reset())
    assert(reset.ok && !reset.data.custom)
    console.log('PASS restore default')
  } finally { await app.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
