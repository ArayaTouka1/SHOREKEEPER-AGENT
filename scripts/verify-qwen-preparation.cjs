const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const assert = require('node:assert/strict')
const ts = require('typescript')
function load(file) {
  const module = { exports: {} }
  const source = ts.transpileModule(fs.readFileSync(path.resolve(__dirname, '../', file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText
  vm.runInNewContext(source, { module, exports: module.exports, require })
  return module.exports
}
const { inspectQwenPreparation, prepareQwenEnvironment } = load('src/main/qwenPreparation.ts')
const { requireQwenConnection } = load('src/shared/qwenPreparation.ts')
fs.mkdirSync(path.resolve(__dirname, '../.verification'), { recursive: true })
const root = fs.mkdtempSync(path.resolve(__dirname, '../.verification/qwen-preparation-'))
const voices = path.resolve(__dirname, '../resources/qwen3voices')
assert.equal(inspectQwenPreparation(root, voices).prepared, false)
assert.equal(prepareQwenEnvironment(root, voices).prepared, true)
const config = path.join(root, 'environment.json')
const before = fs.readFileSync(config, 'utf8')
assert.equal(prepareQwenEnvironment(root, voices).prepared, true)
assert.equal(fs.readFileSync(config, 'utf8'), before)
const state = inspectQwenPreparation(root, voices)
assert.equal(state.downloadConnected, false)
assert.equal(state.inferenceConnected, false)
assert.equal(state.voices, 4)
assert.throws(() => prepareQwenEnvironment(path.join(root, 'missing'), root), /参考音色/)
assert.equal(fs.existsSync(path.join(root, 'missing')), false)
fs.writeFileSync(config, '{broken')
assert.equal(inspectQwenPreparation(root, voices).prepared, false)
assert.throws(() => prepareQwenEnvironment(root, voices), /未覆盖/)
assert.equal(fs.readFileSync(config, 'utf8'), '{broken')
assert.throws(requireQwenConnection, /暂未接入/)
console.log('PASS: preparation, persistence, idempotency, missing voices, corrupt configuration preservation, disconnected download/inference.')
